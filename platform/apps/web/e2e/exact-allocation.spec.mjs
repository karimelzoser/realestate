import {test,expect} from '@playwright/test';
test('assigned exact apartment selection works in English and persists into Arabic mobile RTL',async({page,context},testInfo)=>{
  const base=process.env.E07_WEB_URL??'http://127.0.0.1:3030';
  await context.addCookies([{name:'preneura_session',value:'exact-allocation-browser-token-00000000001',url:base,httpOnly:true,sameSite:'Lax'}]);
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/workspace/allocation');
  await expect(page.getByRole('heading',{name:'Reception & Allocation'})).toBeVisible();
  await expect(page.getByRole('heading',{name:'EOI Type A'})).toBeVisible();
  await page.getByRole('combobox',{name:'Building',exact:true}).selectOption({label:'Building One · B1'});
  const floor=page.getByRole('combobox',{name:'Floor',exact:true});
  await floor.selectOption({index:1});
  await expect(page.getByRole('heading',{name:'B1-F1-U2',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Review exact quote',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Exact apartment quote · B1-F1-U2'})).toBeVisible();
  await expect(page.getByRole('button',{name:'Hold this apartment for 15 minutes'})).toBeDisabled();
  await page.screenshot({path:testInfo.outputPath('english-desktop-quote.png'),fullPage:true});
  await page.getByRole('checkbox',{name:'I confirm the buyer selected this exact apartment and reviewed this quote.'}).check();
  await page.getByRole('button',{name:'Hold this apartment for 15 minutes'}).click();
  await expect(page.getByRole('button',{name:'Create reservation',exact:true})).toBeEnabled();
  await page.getByRole('button',{name:'العربية',exact:true}).click();
  await expect(page.locator('html')).toHaveAttribute('dir','rtl');
  await page.setViewportSize({width:390,height:844});
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('lang','ar');
  await expect(page.getByRole('heading',{name:'عرض سعر الشقة المحددة · B1-F1-U2'})).toBeVisible();
  await expect(page.getByRole('button',{name:'إنشاء الحجز',exact:true})).toBeEnabled();
  await expect(page.getByRole('button',{name:'تغيير الاختيار',exact:true})).toBeVisible();
  const dimensions=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,width:window.innerWidth}));
  expect(dimensions.scroll).toBeLessThanOrEqual(dimensions.width+1);
  await page.screenshot({path:testInfo.outputPath('arabic-mobile-held.png'),fullPage:true});
  const converted=page.waitForResponse(response=>response.url().endsWith('/reservations/from-lock')&&response.request().method()==='POST');
  await page.getByRole('button',{name:'إنشاء الحجز',exact:true}).click();
  const reservationResponse=await converted;
  expect(reservationResponse.status()).toBe(201);
  const reservation=await reservationResponse.json();
  expect(reservation.apartment.apartmentReference).toBe('B1-F1-U2');
  expect(reservation.quotedTotal).toBe('201000.00');
  await expect(page.getByRole('status')).toContainText('تم إنشاء الحجز بالسعر المقبول.');
  expect(errors).toEqual([]);
});
